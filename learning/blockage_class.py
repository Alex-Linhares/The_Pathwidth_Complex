def complementary_pairs(adj: list[int], C: int, n: int):
    """Every complementary pair ``(X1, X2)`` in ``C`` with ``|X1 ∩ X2| ≤ n``:
    ``X2 ⊇ (C \\ X1) ∪ attIn(X1)`` with the surplus inside ``X1 \\ attIn(X1)``."""
    for X1 in subsets_of(C):
        a = att_in(adj, C, X1)
        base = (C & ~X1) | a
        if popcount(a) > n:
            continue
        room = X1 & ~a
        for extra in subsets_of(room):
            if popcount(a) + popcount(extra) <= n:
                yield X1, base | extra


def is_blockage_in(adj: list[int], C: int, n: int, member) -> tuple[bool, str]:
    """Axioms (i)–(iii) of a blockage of order ``n`` in ``C`` for the family
    ``{X ⊆ C : member(X)}``; ``member`` is any predicate on bitmasks. Returns
    ``(ok, reason)``."""
    fam = [X for X in subsets_of(C) if member(X)]
    for X in fam:
        if popcount(att_in(adj, C, X)) > n:
            return False, f"(i) fails on {X:b}"
    famset = set(fam)
    for X in fam:
        for Y in subsets_of(X):
            if Y not in famset and popcount(att_in(adj, C, Y)) <= n:
                return False, f"(ii) fails on {Y:b} ⊆ {X:b}"
    for X1, X2 in complementary_pairs(adj, C, n):
        if (X1 in famset) == (X2 in famset):
            return False, f"(iii) fails on ({X1:b}, {X2:b})"
    return True, ""


def blockage_exists(adj: list[int], C: int, n: int) -> bool:
    """Whether *some* blockage of order ``n`` in ``C`` exists, by the frame
    reformulation: a blockage is an up-set of big sets, so search the
    up-sets' choices separation by separation with backtracking."""
    pairs = list(complementary_pairs(adj, C, n))
    small = [X for X in subsets_of(C) if popcount(att_in(adj, C, X)) <= n]
    status: dict[int, bool] = {}        # True = in B (small), False = big

    def consistent() -> bool:
        for X1, X2 in pairs:
            s1, s2 = status.get(X1), status.get(X2)
            if s1 is not None and s2 is not None and s1 == s2:
                return False
        for X, s in status.items():
            if s:
                for Y in subsets_of(X):
                    if status.get(Y) is False:
                        return False
        return True

    order = sorted(small, key=popcount)

    def rec(i: int) -> bool:
        if i == len(order):
            return True
        X = order[i]
        for s in (True, False):
            status[X] = s
            if consistent() and rec(i + 1):
                return True
            del status[X]
        return False

    return rec(0)


def pathwidth_exact(adj: list[int], C: int | None = None) -> int:
    """Vertex separation of the subgraph induced on ``C`` by the subset DP
    (``fixed_parameter_algorithm/pathwidth.py``'s recurrence, on bitmasks)."""
    n = len(adj)
    C = (1 << n) - 1 if C is None else C
    verts = list(bits(C))
    if not verts:
        return 0
    best = {0: 0}
    for size in range(1, len(verts) + 1):
        nxt: dict[int, int] = {}
        for S, val in best.items():
            for v in verts:
                b = 1 << v
                if S & b:
                    continue
                S2 = S | b
                cost = max(val, popcount(att_in(adj, C, S2)))
                if cost < nxt.get(S2, 1 << 30):
                    nxt[S2] = cost
        best = nxt
    return best[C]


# ----------------------------------------------------------------------------
# the operators (predicates on bitmasks)
# ----------------------------------------------------------------------------


def avoid(adj: list[int], C: int, n: int, big):
    """The family ``{X ⊆ C : |attIn(C, X)| ≤ n and not big(X)}`` as a predicate."""
    return lambda X: (X & ~C) == 0 and popcount(att_in(adj, C, X)) <= n and not big(X)


def clique_big(K: int):
    return lambda X: (K & ~X) == 0


def branch_big(C1: int, C2: int, C3: int, big1, big2, big3):
    def big(X: int) -> bool:
        b = (big1(X & C1), big2(X & C2), big3(X & C3))
        return sum(b) >= 2
    return big


def minor_big(branch_sets: list[int], big_H):
    """``big_H`` is a predicate on bitmasks over ``range(len(branch_sets))``."""
    def big(X: int) -> bool:
        img = 0
        for w, T in enumerate(branch_sets):
            if T & X:
                img |= 1 << w
        return big_H(img)
    return big


def linked(adj: list[int], C: int, A: int, B: int, D: int) -> bool:
    """A connected ``Q ⊆ C \\ D`` adjacent to both ``A`` and ``B`` exists: some
    component of ``G[C \\ D]`` meets ``N(A)`` and ``N(B)``."""
    nA, nB = neighbours(adj, A) & C, neighbours(adj, B) & C
    for Q in components(adj, C & ~D):
        if Q & nA and Q & nB:
            return True
    return False


def is_model(adj: list[int], C: int, branch_sets: list[int], H_adj: list[int]) -> bool:
    for T in branch_sets:
        if T == 0 or (T & ~C) or not is_connected(adj, T):
            return False
    for i, T in enumerate(branch_sets):
        for j, T2 in enumerate(branch_sets):
            if i < j and (T & T2):
                return False
    for a in range(len(branch_sets)):
        for b in bits(H_adj[a]):
            if not (neighbours(adj, branch_sets[a]) & branch_sets[b]):
                return False
    return True


