"""A compact generating class of blockages, its brute-force checks and its ceiling.

Blockages (Bienstock, Robertson, Seymour & Thomas 1991, Section 2; the weak half
``blockage of order n => pathwidth >= n`` is ``lean/MOSPFormalization/Blockage.lean``)
are the dual of pathwidth. This module is the computational side of
``lean/MOSPFormalization/BlockageClass.lean`` and of ``reports/blockage_class.md``.

**Convention.** Everything is relative to a vertex set ``C`` of the graph ``G``
(``C = V`` is the ordinary notion): for ``X ⊆ C``, ``attIn(C, X)`` is the set of
vertices of ``X`` with a neighbour in ``C \\ X``; ``(X1, X2)`` is complementary in
``C`` when ``X1 ∪ X2 = C`` and ``attIn(C, X1) ⊆ X2``; a blockage of order ``n`` in
``C`` is a family ``B`` of subsets of ``C`` with (i) ``|attIn| ≤ n`` on members,
(ii) downward closed among subsets with ``|attIn| ≤ n``, (iii) exactly one side
of every complementary pair with ``|X1 ∩ X2| ≤ n``. This is the Lean file's
``≤ n`` reading of the paper's axioms (``Blockage.lean``), under which a blockage
of order ``n`` exists iff ``pw ≥ n`` (checked there to 4 vertices, here to 6).

**Frames.** Every blockage is determined by its *big* sets: ``X`` is big when
``|attIn(C, X)| ≤ n`` and ``X ∉ B``; by (ii) bigness is upward closed among
small-attachment sets, so ``B = avoid(C, n, big) := {X ⊆ C : |attIn| ≤ n, not
big(X)}`` for any monotone predicate ``big`` agreeing with it there. The class
here is generated by three operators on monotone predicates, each a theorem
of ``BlockageClass.lean``:

* ``clique``: ``K ⊆ C`` a clique with ``|K| ≥ n + 1``; ``big(X) := K ⊆ X``.
* ``minor``: a minor model ``T : W → subsets of C`` (disjoint, nonempty,
  connected branch sets, an edge of ``G`` behind every edge of ``H``) and a
  frame ``big_H`` of order ``n`` on all of ``H``; ``big(X) := big_H({w : T(w)
  meets X})``.
* ``branch`` (the linked branch lemma of ``Sandwich.lean`` as a blockage): three
  disjoint connected ``C1, C2, C3 ⊆ C`` carrying frames of order ``k``, every
  pair ``(i, j)`` joined by a connected ``Q ⊆ C`` disjoint from the third branch
  and adjacent to both; ``big(X) := at least two of big_i(X ∩ C_i)``; order
  ``k + 1``.

**The ceiling** of the class on a graph (``ceiling``) is the largest order any
certificate built from the three operators reaches. By minor monotonicity it
is ``max(had(G) − 1, 1 + max{t : three pairwise disjoint, pairwise linked,
connected U_i with ceiling(G[U_i]) ≥ t})`` with ``had`` the Hadwiger number
(``reports/blockage_class.md`` §2.4), computed exactly here by recursion over
induced subgraphs with a memo on nauty certificates; feasible to about 11
vertices. ``counting_upper_bound`` is the arithmetic ceiling used at 20–40
customers, where the recursion is out of reach.

Run the checks and the census from the command line:

    python3 -m learning.blockage_class --stage check        # operator statements by brute force, to 6 vertices
    python3 -m learning.blockage_class --stage census       # the pw > tw graphs to 9 vertices and the pw − tw = 2 ones to 11
    python3 -m learning.blockage_class --stage corpus       # the 197 bound-gap instances at ≤ 40 customers
    python3 -m pytest tests/test_blockage_class.py -q
"""
