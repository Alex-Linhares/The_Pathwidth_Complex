def atlas(max_n: int):
    """Every graph of networkx's atlas with at most ``max_n`` vertices, as bitmasks."""
    from networkx.generators.atlas import graph_atlas_g

    for g in graph_atlas_g():
        if g.number_of_nodes() <= max_n and g.number_of_nodes() >= 1:
            yield adj_from_nx(g)


def connected_subsets(adj: list[int], C: int):
    return [U for U in subsets_of(C) if U and is_connected(adj, U)]


def check_clique(adj: list[int], n_max: int = 4) -> list[str]:
    bad = []
    n = len(adj)
    V = (1 << n) - 1
    for C in subsets_of(V):
        if C == 0:
            continue
        for K in subsets_of(C):
            if K and is_clique(adj, K):
                for order in range(0, popcount(K)):
                    ok, why = is_blockage_in(adj, C, order, avoid(adj, C, order, clique_big(K)))
                    if not ok:
                        bad.append(f"clique K={K:b} C={C:b} n={order}: {why}")
    return bad


def check_branch(adj: list[int], rng: random.Random, samples: int = 40,
                 stats: dict | None = None) -> list[str]:
    """Three disjoint connected branches, each carrying a *clique* frame (the
    base case), pairwise linked; the output must be a blockage of order k + 1
    in every C containing them. Unlinked triples are the control: ``stats``
    counts how often the conclusion then fails (the hypothesis is needed)."""
    bad = []
    n = len(adj)
    V = (1 << n) - 1
    conn = connected_subsets(adj, V)
    frames = []                                     # (U, k, big) with avoid(U,k,big) a blockage in U
    for U in conn:
        for K in subsets_of(U):
            if K and is_clique(adj, K):
                frames.append((U, popcount(K) - 1, clique_big(K)))
    by_k: dict[int, list] = {}
    for U, k, big in frames:
        by_k.setdefault(k, []).append((U, big))
    all_C = list(subsets_of(V))
    for k, lst in by_k.items():
        trip = [t for t in itertools.combinations(lst, 3)
                if not (t[0][0] & t[1][0]) and not (t[0][0] & t[2][0]) and not (t[1][0] & t[2][0])]
        rng.shuffle(trip)
        for (A, bA), (B, bB), (D, bD) in trip[:samples]:
            for C in (V,) + tuple(rng.sample(all_C, min(3, len(all_C)))):
                if (A | B | D) & ~C:
                    continue
                lk = linked(adj, C, A, B, D) and linked(adj, C, A, D, B) and linked(adj, C, B, D, A)
                big = branch_big(A, B, D, bA, bB, bD)
                ok, why = is_blockage_in(adj, C, k + 1, avoid(adj, C, k + 1, big))
                if stats is not None:
                    key = ("linked" if lk else "unlinked") + ("_ok" if ok else "_fail")
                    stats[key] = stats.get(key, 0) + 1
                if lk and not ok:
                    bad.append(f"branch A={A:b} B={B:b} D={D:b} C={C:b} k={k}: {why}")
    return bad


def check_minor(adj: list[int], rng: random.Random, samples: int = 30) -> list[str]:
    """Random minor models whose quotient carries a clique frame; the pulled
    back frame must be a blockage in every C containing the branch sets."""
    bad = []
    n = len(adj)
    V = (1 << n) - 1
    conn = connected_subsets(adj, V)
    for _ in range(samples):
        w = rng.randint(1, min(4, n))
        sets = []
        used = 0
        for _ in range(w):
            cands = [U for U in conn if not (U & used)]
            if not cands:
                break
            U = rng.choice(cands)
            sets.append(U)
            used |= U
        w = len(sets)
        H_adj = [0] * w
        for a in range(w):
            for b in range(a + 1, w):
                if neighbours(adj, sets[a]) & sets[b]:
                    H_adj[a] |= 1 << b
                    H_adj[b] |= 1 << a
        for K in subsets_of((1 << w) - 1):
            if K and is_clique(H_adj, K):
                order = popcount(K) - 1
                for C in (V, used):
                    big = minor_big(sets, clique_big(K))
                    ok, why = is_blockage_in(adj, C, order, avoid(adj, C, order, big))
                    if not ok:
                        bad.append(f"minor sets={[bin(s) for s in sets]} K={K:b} C={C:b}: {why}")
    return bad


def check_duality(adj: list[int]) -> list[str]:
    """Blockage of order n exists in C iff pw(G[C]) ≥ n (both halves, C = V)."""
    bad = []
    n = len(adj)
    V = (1 << n) - 1
    pw = pathwidth_exact(adj)
    for order in range(0, n + 1):
        ex = blockage_exists(adj, V, order)
        if ex != (pw >= order):
            bad.append(f"duality n={order} exists={ex} pw={pw}")
    return bad


def run_checks(max_n: int = 6, seed: int = 0, log=print) -> dict:
    rng = random.Random(seed)
    counts = {"graphs": 0, "clique_bad": 0, "branch_bad": 0, "minor_bad": 0, "duality_bad": 0}
    t0 = time.time()
    for adj in atlas(max_n):
        n = len(adj)
        counts["graphs"] += 1
        for name, fn in (("clique", lambda a: check_clique(a)),
                         ("branch", lambda a: check_branch(a, rng, stats=counts)),
                         ("minor", lambda a: check_minor(a, rng))):
            if name == "clique" and n > 5:
                continue                              # every (C, K) pair: 3^n families; to 5 vertices
            bad = fn(adj)
            counts[f"{name}_bad"] += len(bad)
            for b in bad[:3]:
                log(f"  {b}")
        if n <= 5:
            bad = check_duality(adj)
            counts["duality_bad"] += len(bad)
            for b in bad[:3]:
                log(f"  {b}")
    counts["seconds"] = round(time.time() - t0, 1)
    log(f"checks: {counts}")
    return counts


