def popcount(x: int) -> int:
    return bin(x).count("1")


def bits(x: int):
    while x:
        b = x & -x
        yield b.bit_length() - 1
        x ^= b


def adj_from_edges(n: int, edges) -> list[int]:
    adj = [0] * n
    for u, v in edges:
        if u != v:
            adj[u] |= 1 << v
            adj[v] |= 1 << u
    return adj


def adj_from_graph6(text: str) -> list[int]:
    import networkx as nx

    g = nx.from_graph6_bytes(text.strip().encode())
    return adj_from_edges(g.number_of_nodes(), g.edges())


def adj_from_nx(graph) -> list[int]:
    nodes = sorted(graph.nodes())
    index = {v: i for i, v in enumerate(nodes)}
    return adj_from_edges(len(nodes), ((index[u], index[v]) for u, v in graph.edges()))


def neighbours(adj: list[int], X: int) -> int:
    r = 0
    for v in bits(X):
        r |= adj[v]
    return r


def is_connected(adj: list[int], X: int) -> bool:
    """The subgraph induced on ``X`` is connected (the empty set is not)."""
    if X == 0:
        return False
    start = X & -X
    seen = start
    frontier = start
    while frontier:
        nxt = neighbours(adj, frontier) & X & ~seen
        seen |= nxt
        frontier = nxt
    return seen == X


def components(adj: list[int], X: int) -> list[int]:
    out = []
    rest = X
    while rest:
        start = rest & -rest
        seen = start
        frontier = start
        while frontier:
            nxt = neighbours(adj, frontier) & X & ~seen
            seen |= nxt
            frontier = nxt
        out.append(seen)
        rest &= ~seen
    return out


def att_in(adj: list[int], C: int, X: int) -> int:
    """The attachments of ``X`` relative to ``C``: vertices of ``X`` with a
    neighbour in ``C \\ X``."""
    outside = C & ~X
    r = 0
    for v in bits(X):
        if adj[v] & outside:
            r |= 1 << v
    return r


def is_clique(adj: list[int], K: int) -> bool:
    for v in bits(K):
        if (K & ~(1 << v)) & ~adj[v]:
            return False
    return True


def clique_number(adj: list[int], C: int | None = None) -> int:
    n = len(adj)
    C = (1 << n) - 1 if C is None else C
    best = 0

    def grow(K: int, cand: int) -> None:
        nonlocal best
        if popcount(K) + popcount(cand) <= best:
            return
        if cand == 0:
            best = max(best, popcount(K))
            return
        while cand:
            v = (cand & -cand).bit_length() - 1
            cand &= ~(1 << v)
            grow(K | (1 << v), cand & adj[v])
            if popcount(K) + 1 + popcount(cand) <= best:
                return

    grow(0, C)
    return best


def subsets_of(mask: int):
    """Every submask of ``mask``, ``0`` included."""
    sub = mask
    while True:
        yield sub
        if sub == 0:
            return
        sub = (sub - 1) & mask


