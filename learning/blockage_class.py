def canon(adj: list[int], U: int) -> bytes:
    """nauty's certificate of ``G[U]``, with the vertex count prepended."""
    import pynauty

    verts = list(bits(U))
    index = {v: i for i, v in enumerate(verts)}
    k = len(verts)
    if k == 0:
        return b"0"
    g = pynauty.Graph(k)
    for v in verts:
        nb = [index[u] for u in bits(adj[v] & U) if u > v]
        if nb:
            g.connect_vertex(index[v], nb)
    return bytes([k]) + pynauty.certificate(g)


def induced(adj: list[int], U: int) -> list[int]:
    verts = list(bits(U))
    index = {v: i for i, v in enumerate(verts)}
    out = [0] * len(verts)
    for v in verts:
        for u in bits(adj[v] & U):
            out[index[v]] |= 1 << index[u]
    return out


def contract(adj: list[int], u: int, v: int) -> list[int]:
    """Contract the edge ``uv`` into ``u`` and drop ``v`` (vertices relabelled
    to ``0..n-2`` in order)."""
    n = len(adj)
    merged = list(adj)
    merged[u] = (adj[u] | adj[v]) & ~(1 << u) & ~(1 << v)
    for y in bits(adj[v]):
        if y != u:
            merged[y] |= 1 << u
    keep = [x for x in range(n) if x != v]
    index = {x: i for i, x in enumerate(keep)}
    out = [0] * (n - 1)
    for x in keep:
        for y in bits(merged[x] & ~(1 << v)):
            out[index[x]] |= 1 << index[y]
    return out


class Ceiling:
    """The class's ceiling with a memo shared across graphs (nauty certificates)."""

    def __init__(self) -> None:
        self.had_memo: dict[bytes, int] = {}
        self.ceil_memo: dict[bytes, int] = {}
        self.calls = 0

    def hadwiger(self, adj: list[int]) -> int:
        n = len(adj)
        if n == 0:
            return 0
        key = canon(adj, (1 << n) - 1)
        got = self.had_memo.get(key)
        if got is not None:
            return got
        best = clique_number(adj)
        if best < n:                                   # a non-complete graph may gain by contracting
            seen = set()
            for u in range(n):
                for v in bits(adj[u]):
                    if v > u:
                        h = contract(adj, u, v)
                        k2 = canon(h, (1 << (n - 1)) - 1)
                        if k2 in seen:
                            continue
                        seen.add(k2)
                        best = max(best, self.hadwiger(h))
                        if best == n:
                            break
                if best == n:
                    break
        self.had_memo[key] = best
        return best

    def ceiling(self, adj: list[int]) -> int:
        """``max(had − 1, 1 + max{t : a linked triple of connected induced
        subgraphs of ceiling ≥ t})``; the empty graph has ceiling 0 by convention
        of the DP (it is never a branch)."""
        n = len(adj)
        if n == 0:
            return 0
        V = (1 << n) - 1
        key = canon(adj, V)
        got = self.ceil_memo.get(key)
        if got is not None:
            return got
        self.calls += 1
        value = self.hadwiger(adj) - 1
        # ceiling of every proper connected induced subgraph
        sub: dict[int, int] = {}
        for U in subsets_of(V):
            if U and U != V and is_connected(adj, U):
                sub[U] = self.ceiling(induced(adj, U))
        value = max(value, self.branch_term(adj, V, sub))
        self.ceil_memo[key] = value
        return value

    @staticmethod
    def branch_term(adj: list[int], V: int, sub: dict[int, int]) -> int:
        """``1 + t`` for the largest ``t`` with three pairwise disjoint, pairwise
        linked members of ``M_t`` (the minimal connected sets of value ≥ t);
        ``0`` when no linked triple exists at all (``t = −1`` is impossible)."""
        if not sub:
            return 0
        levels = sorted(set(sub.values()), reverse=True)
        for t in levels:
            members = [U for U, val in sub.items() if val >= t]
            minimal = [U for U in members if not any(W != U and (W & ~U) == 0 for W in members)]
            minimal.sort(key=popcount)
            for A, B, D in itertools.combinations(minimal, 3):
                if (A & B) or (A & D) or (B & D):
                    continue
                if linked(adj, V, A, B, D) and linked(adj, V, A, D, B) and linked(adj, V, B, D, A):
                    return t + 1
        return 0


def ceiling_by_minor_closure(adj: list[int], cache: dict | None = None) -> int:
    """An independent, slower evaluation of the ceiling for the implementation
    check: maximum over *every* minor ``H`` (by single-step deletions and
    contractions, memoised on certificates) of the local value ``max(ω(H) − 1,
    1 + max linked triples of connected induced subgraphs of H with their own
    closure ceiling)``."""
    cache = {} if cache is None else cache
    n = len(adj)
    if n == 0:
        return 0
    V = (1 << n) - 1
    key = canon(adj, V)
    if key in cache:
        return cache[key]
    local = clique_number(adj) - 1
    sub = {U: ceiling_by_minor_closure(induced(adj, U), cache)
           for U in subsets_of(V) if U and U != V and is_connected(adj, U)}
    local = max(local, Ceiling.branch_term(adj, V, sub))
    best = local
    for u in range(n):
        for v in bits(adj[u]):
            if v > u:
                best = max(best, ceiling_by_minor_closure(contract(adj, u, v), cache))
                h = list(adj)
                h[u] &= ~(1 << v)
                h[v] &= ~(1 << u)
                best = max(best, ceiling_by_minor_closure(h, cache))
    for v in range(n):
        best = max(best, ceiling_by_minor_closure(induced(adj, V & ~(1 << v)), cache))
    cache[key] = best
    return best


# ----------------------------------------------------------------------------
# counting bounds at sizes where the recursion is out of reach
# ----------------------------------------------------------------------------


def min_vertices(t: int, had: int) -> int:
    """The fewest vertices a certificate of order ``t`` can occupy in a graph
    with Hadwiger number ``≤ had``: a clique minor when ``t + 1 ≤ had``, else
    three branches of order ``t − 1``; the connectors may lie inside the
    branches, so they cost nothing."""
    if t <= 0:
        return 1
    if t + 1 <= had:
        return t + 1
    return 3 * min_vertices(t - 1, had)


def branch_excluded(t: int, n: int, had_upper: int, tau: int, edges: int) -> bool:
    """No branch certificate of order ``t`` fits: three disjoint connected sets
    of order ``t − 1`` need ``3 · min_vertices(t − 1)`` vertices, vertex cover
    ``3 (t − 1)`` and, when their certificates are clique minors (``t ≤
    had_upper``), ``3 · C(t, 2)`` edges."""
    if 3 * min_vertices(t - 1, had_upper) > n:
        return True
    if 3 * (t - 1) > tau:
        return True
    if t <= had_upper and 3 * (t * (t - 1) // 2) > edges:
        return True
    return False


def counting_upper_bound(n: int, had_upper: int, tau: int | None = None, edges: int | None = None) -> int:
    """The largest order the class can reach on a graph with ``n`` vertices,
    Hadwiger number ``≤ had_upper``, vertex cover number ``tau`` and ``edges``
    edges: the clique term is ``≤ had_upper − 1``; a branch certificate of order
    ``t`` needs three disjoint connected sets of pathwidth ``≥ t − 1``, hence
    ``3 · min_vertices(t − 1) ≤ n``, ``3 (t − 1) ≤ tau`` (``pw ≤ τ`` on each,
    ``τ`` superadditive over disjoint sets) and, when the sub-certificates are
    clique minors, ``3 · C(t, 2) ≤ edges``."""
    best = had_upper - 1
    t = best + 1
    while True:
        if 3 * min_vertices(t - 1, had_upper) > n:
            break
        if tau is not None and 3 * (t - 1) > tau:
            break
        if edges is not None and t <= had_upper and 3 * (t * (t - 1) // 2) > edges:
            break
        best = t
        t += 1
    return best


